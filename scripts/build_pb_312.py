#!/usr/bin/env python3
"""铅(PB) 3.1.2 海外矿·分国别总量子页 · v1 · 3 图全真数据（板块3·供给·第2子节点）。

图1 全球铅矿产量 vs 中国占比（chart_dual）：j311_ilm 全球铅矿产量 + i40 中国海关铅精矿进口量
     —— 全球产量反映海外矿端总量,进口量反映中国从海外获取的份额
图2 全球铅矿产量季节图（chart_line_t seasonal）：近5年历年线,观察全球产量季节性
图3 进口铅精矿分港口结构（chart_dual）：i16 防城到港 + i5 港口库存
     —— 分港口的到港与库存结构反映海外矿供应的地理分布

数据源：ILZSG 全球铅矿产量(ID00299370, 月) + 中国海关铅精矿进口量(a10017055, 月) + SMM 铅矿到港防城(a10127618, 月) + Mysteel 进口铅精矿港口库存(ID01167590, 周)。
备用（未入正主）：海外矿分国别数据(知几无铅专用分国别矿端产量序列,需外部源补充)。
"""
from chart_kits import (load_metric, pairs, latest, chart_line_t, chart_dual,
                        page_html, write_html, make_crumb)

CIDS = ["echart_312_c1", "echart_312_c2", "echart_312_c3"]

m_ilm = load_metric("j311_ilm")
m_imp = load_metric("i40")
m_port = load_metric("i16")
m_inv = load_metric("i5")

d_ilm = pairs(m_ilm)
d_imp = pairs(m_imp)
d_port = pairs(m_port)
d_inv = pairs(m_inv)

print("[POINTS] 全球铅矿产量=%d 海关进口=%d 到港防城=%d 港口库存=%d" % (
    len(d_ilm), len(d_imp), len(d_port), len(d_inv)))

# === 图1：全球铅矿产量 vs 中国海关进口 ===
h1, j1 = chart_dual(
    "echart_312_c1",
    "全球铅矿产量 vs 中国海关进口（3.1.2 正主）",
    "ILZSG 全球铅矿产量 · 月 · 千吨 + 中国海关铅精矿进口量 · 月 · 吨 · %d/%d 点 · 至 %s" % (
        len(d_ilm), len(d_imp), latest(m_ilm)),
    d_ilm, "#7a8c5b", "全球铅矿产量", "千吨",
    d_imp, "#5b98c9", "中国海关进口", "吨",
    "什么时候看：3.1.2 海外矿分国别总量的正主图——全球产量反映海外矿端总量,中国进口量反映中国从海外获取的份额。<br>"
    "怎么看：全球产量上行+中国进口上行=海外矿供应充裕+中国获取份额增加=海外矿端宽松。"
    "全球产量下行+中国进口下行=海外矿供应收紧+中国获取份额减少=海外矿端偏紧。"
    "两条线背离=中国进口份额变化(获取更多或更少海外矿)。"
    "注：海外矿分国别数据知几无铅专用序列,全球产量+中国进口为最佳代理。"
)

# === 图2：全球铅矿产量季节图 ===
h2, j2 = chart_line_t(
    "echart_312_c2",
    "全球铅矿产量·季节图",
    "ILZSG 全球铅矿产量 · 月 · 千吨 · %d 点(2014起) · 至 %s" % (
        len(d_ilm), latest(m_ilm)),
    "#7a8c5b", d_ilm,
    "什么时候看：判断全球铅矿产量的月度季节性规律。<br>"
    "怎么看：Q1(春节后补库)全球产量偏高,Q3(淡季)偏低。"
    "若某年全球产量线整体抬升=海外矿端结构性改善;若下移=海外矿端结构性收缩。"
)

# === 图3：进口铅精矿分港口结构 ===
h3, j3 = chart_dual(
    "echart_312_c3",
    "进口铅精矿分港口结构（到港 vs 库存）",
    "SMM 铅矿到港-防城港 · 月 · 万吨 + Mysteel 进口铅精矿港口库存 · 周 · 万吨 · %d/%d 点 · 至 %s" % (
        len(d_port), len(d_inv), latest(m_port)),
    d_port, "#5b98c9", "防城到港", "万吨",
    d_inv, "#e06c75", "港口库存", "万吨",
    "什么时候看：判断海外矿供应的地理分布——防城港是最大铅矿进口港,到港量与港口库存反映供应地理结构。<br>"
    "怎么看：防城到港上行=海外矿供应充裕;港口库存上行=供应缓冲充足。"
    "到港下行+库存下行=海外矿供应地理结构收紧。"
    "注：分国别数据知几无铅专用序列,分港口为最佳代理。"
)

NOTE = """<strong style="color:#c9d1d9">3.1.2 定义：</strong>海外矿·分国别总量 = 全球铅矿产量(海外矿代理) + 中国海关铅精矿进口量 + 分港口结构,判断海外矿供应的地理分布与份额变化。<br>
<strong style="color:#c9d1d9">指标组（正主）：</strong>j311_ilm ILZSG全球铅矿产量(千吨/月) + i40 中国海关铅精矿进口量(吨/月)。<br>
<strong style="color:#c9d1d9">辅助指标：</strong>i16 铅矿到港防城(万吨/月, 294点) · i5 进口铅精矿港口库存(万吨/周, 432点)。<br>
<strong style="color:#c9d1d9">排除项（归属其他节点）：</strong>海外矿财报产量 → 3.1.1正主 · 国内矿产量 → 3.1.3正主 · 铅精矿进口量 → 3.1.4正主 · TC加工费 → 3.1.5正主。<br>
<strong style="color:#c9d1d9">数据源：</strong>ILZSG 全球铅矿产量(ID00299370, 月度102点/2014起) + 中国海关铅精矿进口量(a10017055, 月度103点/2018起) + SMM 铅矿到港防城(a10127618, 月度294点/2019起) + Mysteel 进口铅精矿港口库存(ID01167590, 周度432点/2022起)。<br>
<strong style="color:#c9d1d9">数据质量：</strong>全球铅矿产量102点；海关进口103点；防城到港294点；港口库存432点。<br>
<strong style="color:#c9d1d9">3.x 边界：</strong>3.1.1=海外矿财报产量 · 3.1.2=分国别总量 · 3.1.3=国内矿产量 · 3.1.4=矿进口量 · 3.1.5=TC加工费 · 3.2.1=精炼产量 · 3.2.2=开工率检修 · 3.2.3=再生供应(已上线) · 3.2.4=冶炼利润供应弹性。"""

html = page_html(
    "铅(PB) 3.1.2 海外矿·分国别总量",
    make_crumb("铅", "PB", "3", "供给", "3.1.2", "海外矿·分国别总量", "1", 3),
    "ILZSG/海关",
    h1, h2, h3, NOTE,
    "有色金属产业指标树 · 铅(PB) 3.1.2 海外矿·分国别总量 · v1（3 图全真数据 · 全球产量vs中国进口 · 全球产量季节图 · 分港口结构）· indicators_v1.json v3.1",
    j1 + "\n" + j2 + "\n" + j3,
    CIDS,
    nav_back='<a href="pb_3_overview.html">← 回板块3总览</a> <a href="index.html">← 回主站</a>',
)
