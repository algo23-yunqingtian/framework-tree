#!/usr/bin/env python3
"""铅(PB) 3.1.3 国内矿产量子页 · v1 · 3 图全真数据（板块3·供给·第3子节点）。

图1 青海铅精矿产量时序（chart_line_t）：j313_qh NBS铅精矿产量-青海(月) —— 青海为中国铅矿第一大省,为国内矿产量最佳代理
图2 青海铅精矿产量季节图（chart_line_t seasonal）：近5年历年线,观察国内矿产量季节性
图3 国内铅精矿原料库存（chart_line_t）：i10 铅精矿原料库存-中国(月) —— 国内矿端的库存缓冲,反映原料供应与冶炼消耗平衡

数据源：NBS 铅精矿产量-青海(a10026726, 月) + Mysteel 铅精矿原料库存-中国(ID01590235, 月)。
备用（未入正主）：SMM铅精矿产量-中国-预测值(a12802655, 年)——年度数据,不适合月度图。
"""
from chart_kits import (load_metric, pairs, latest, chart_line_t,
                        page_html, write_html, make_crumb)

CIDS = ["echart_313_c1", "echart_313_c2", "echart_313_c3"]

m_qh = load_metric("j313_qh")
m_inv = load_metric("i10")

d_qh = pairs(m_qh)
d_inv = pairs(m_inv)

print("[POINTS] 青海铅矿产量=%d 国内原料库存=%d" % (
    len(d_qh), len(d_inv)))

# === 图1：青海铅精矿产量 ===
h1, j1 = chart_line_t(
    "echart_313_c1",
    "青海铅精矿产量（3.1.3 正主）",
    "NBS 铅精矿产量-青海 · 月 · 万吨 · %d 点(2020起) · 至 %s" % (
        len(d_qh), latest(m_qh)),
    "#7a8c5b", d_qh,
    "什么时候看：3.1.3 国内矿产量的正主图——青海为中国铅矿第一大省,产量是国内矿端供应的核心指标。<br>"
    "怎么看：青海产量上行=国内矿端供应改善=原生冶炼原料充裕=冶炼端有动力维持开工。"
    "产量下行=国内矿端供应收紧=原生冶炼原料偏紧=减产风险。"
    "注：知几无全国铅矿产量月度序列,青海为最佳代理(占国内铅矿产量约30%)。"
)

# === 图2：青海铅精矿产量季节图 ===
h2, j2 = chart_line_t(
    "echart_313_c2",
    "青海铅精矿产量·季节图",
    "NBS 铅精矿产量-青海 · 月 · 万吨 · %d 点(2020起) · 至 %s" % (
        len(d_qh), latest(m_qh)),
    "#7a8c5b", d_qh,
    "什么时候看：判断国内铅矿产量的月度季节性规律——国内矿端受气候、环保政策影响。<br>"
    "怎么看：Q2/Q3(夏季)产量偏高(矿山正常开采)；Q1(春节)偏低(节前停产)。"
    "若某年产量线整体抬升=国内矿端产能扩张;若下移=环保限产或资源枯竭。"
)

# === 图3：国内铅精矿原料库存 ===
h3, j3 = chart_line_t(
    "echart_313_c3",
    "国内铅精矿原料库存·季节图",
    "Mysteel 铅精矿原料库存-中国 · 月 · 万吨 · %d 点(2022起) · 至 %s" % (
        len(d_inv), latest(m_inv)),
    "#e06c75", d_inv,
    "什么时候看：判断国内矿端的库存缓冲——原料库存是国内产量与冶炼消耗之间的蓄水池。<br>"
    "怎么看：原料库存上行=国内矿端供应充裕或冶炼消耗放缓=短期原料供应宽松。"
    "原料库存下行=国内矿端供应收紧或冶炼消耗加快=短期原料供应偏紧。"
    "与产量结合看：库存上行+产量上行=国内矿端供应充裕;库存下行+产量下行=国内矿端供应收紧。"
)

NOTE = """<strong style="color:#c9d1d9">3.1.3 定义：</strong>国内矿产量 = 青海铅精矿产量(国内矿端代理) + 国内铅精矿原料库存,判断国内矿端供应基本面与库存缓冲。<br>
<strong style="color:#c9d1d9">指标组（正主）：</strong>j313_qh NBS铅精矿产量-青海(万吨/月) —— 知几无全国铅矿产量月度序列,青海为最佳代理。<br>
<strong style="color:#c9d1d9">辅助指标：</strong>i10 铅精矿原料库存-中国(万吨/月, 227点)。<br>
<strong style="color:#c9d1d9">排除项（归属其他节点）：</strong>海外矿财报产量 → 3.1.1正主 · 海外矿分国别 → 3.1.2正主 · 铅精矿进口量 → 3.1.4正主 · TC加工费 → 3.1.5正主 · 铅精矿产量预测值(a12802655, 年度数据,入备用库)。<br>
<strong style="color:#c9d1d9">数据源：</strong>NBS 铅精矿产量-青海(a10026726, 月度65点/2020起) + Mysteel 铅精矿原料库存-中国(ID01590235, 月度227点/2022起)。<br>
<strong style="color:#c9d1d9">数据质量：</strong>青海铅矿产量65点(2020-01起)；国内原料库存227点(2022-08起)。<br>
<strong style="color:#c9d1d9">3.x 边界：</strong>3.1.1=海外矿财报产量 · 3.1.2=分国别总量 · 3.1.3=国内矿产量 · 3.1.4=矿进口量 · 3.1.5=TC加工费 · 3.2.1=精炼产量 · 3.2.2=开工率检修 · 3.2.3=再生供应(已上线) · 3.2.4=冶炼利润供应弹性。"""

html = page_html(
    "铅(PB) 3.1.3 国内矿产量",
    make_crumb("铅", "PB", "3", "供给", "3.1.3", "国内矿产量", "1", 3),
    "NBS/Mysteel",
    h1, h2, h3, NOTE,
    "有色金属产业指标树 · 铅(PB) 3.1.3 国内矿产量 · v1（3 图全真数据 · 青海铅矿产量 · 产量季节图 · 国内原料库存）· indicators_v1.json v3.1",
    j1 + "\n" + j2 + "\n" + j3,
    CIDS,
    nav_back='<a href="pb_3_overview.html">← 回板块3总览</a> <a href="index.html">← 回主站</a>',
)
write_html("pb_313_domestic_mine.html", html)
