"""铅(PB) 3.1.1 海外矿·财报产量子页 · v1 · 3 图全真数据（板块3·供给·第1子节点）。

图1 全球铅矿产量时序（chart_line_t）：j311_ilm ILZSG全球铅矿产量(月) —— 海外矿无铅专用财报序列,全球为最佳代理
图2 铅矿到港(防城)时序（chart_line_t）：i16 防城港铅矿到港(月) —— 海外矿到港实况,海外供给落地验证
图3 进口铅精矿港口库存（chart_line_t）：i5 进口铅精矿港口库存(周) —— 海外矿供应的库存缓冲,反映到港消化节奏

数据源：ILZSG 全球铅矿产量(ID00299370, 月) + SMM 铅矿到港防城(a10127618, 月) + Mysteel 进口铅精矿港口库存(ID01167590, 周)。
备用（未入正主）：海外铅矿分国别数据(知几无铅专用分国别矿端产量序列,需外部源补充)。
"""
from chart_kits import (load_metric, pairs, latest, chart_line_t,
                        page_html, write_html, make_crumb)

CIDS = ["echart_311_c1", "echart_311_c2", "echart_311_c3"]

m_ilm = load_metric("j311_ilm")
m_port = load_metric("i16")
m_inv = load_metric("i5")

d_ilm = pairs(m_ilm)
d_port = pairs(m_port)
d_inv = pairs(m_inv)

print("[POINTS] 全球铅矿产量=%d 到港防城=%d 港口库存=%d" % (
    len(d_ilm), len(d_port), len(d_inv)))

# === 图1：全球铅矿产量 ===
h1, j1 = chart_line_t(
    "echart_311_c1",
    "全球铅矿产量（3.1.1 正主）",
    "ILZSG 全球铅矿产量 · 月 · 千吨 · %d 点(2014起) · 至 %s" % (
        len(d_ilm), latest(m_ilm)),
    "#7a8c5b", d_ilm,
    "什么时候看：3.1.1 海外矿财报产量的正主图——判断全球铅矿供应基本面。<br>"
    "怎么看：全球铅矿产量上行=海外矿供应改善=海外矿端宽松=进口窗口打开。"
    "产量下行=海外矿端偏紧=原料供应收缩=进口窗口收紧。"
    "海外矿无铅专用财报序列,ILZSG全球数据为最佳代理(铅为副产品,全球口径覆盖海外矿端)。"
)

# === 图2：铅矿到港(防城) ===
h2, j2 = chart_line_t(
    "echart_311_c2",
    "铅矿到港(防城)·季节图",
    "SMM 铅矿到港-防城港 · 月 · 万吨 · %d 点(2019起) · 至 %s" % (
        len(d_port), latest(m_port)),
    "#5b98c9", d_port,
    "什么时候看：判断海外铅矿到港实况——防城港是中国最大的铅矿进口港,到港量是海外矿供应落地的直接证据。<br>"
    "怎么看：到港量上行=海外矿供应充裕=冶炼厂原料库存恢复=冶炼端有动力维持开工。"
    "到港量下行=海外矿供应收紧=冶炼厂原料库存消耗=减产风险。"
    "季节性：Q1(春节后补库)到港偏高,Q3(淡季)偏低。"
)

# === 图3：进口铅精矿港口库存 ===
h3, j3 = chart_line_t(
    "echart_311_c3",
    "进口铅精矿港口库存·季节图",
    "Mysteel 进口铅精矿港口库存(周) · %d 点(2022起) · 至 %s" % (
        len(d_inv), latest(m_inv)),
    "#e06c75", d_inv,
    "什么时候看：判断海外矿供应的库存缓冲——港口库存是到港量与冶炼消耗之间的蓄水池。<br>"
    "怎么看：港口库存上行=到港充裕或冶炼消耗放缓=短期原料供应宽松。"
    "港口库存下行=到港收紧或冶炼消耗加快=短期原料供应偏紧。"
    "与到港量结合看：库存上行+到港上行=供应充裕;库存下行+到港下行=供应收紧。"
)

NOTE = """<strong style="color:#c9d1d9">3.1.1 定义：</strong>海外矿·财报产量 = 全球铅矿产量(海外矿代理) + 铅矿到港(防城) + 进口铅精矿港口库存，判断海外矿供应基本面与到港消化节奏。<br>
<strong style="color:#c9d1d9">指标组（正主）：</strong>j311_ilm ILZSG全球铅矿产量(千吨/月) —— 海外矿无铅专用财报序列,全球数据为最佳代理。<br>
<strong style="color:#c9d1d9">辅助指标：</strong>i16 铅矿到港防城(万吨/月, 294点) · i5 进口铅精矿港口库存(万吨/周, 432点)。<br>
<strong style="color:#c9d1d9">排除项（归属其他节点）：</strong>海外矿分国别数据 → 3.1.2正主 · 铅精矿进口量 → 3.1.4正主 · TC加工费 → 3.1.5正主 · 国内矿产量 → 3.1.3正主。<br>
<strong style="color:#c9d1d9">数据源：</strong>ILZSG 全球铅矿产量(ID00299370, 月度102点/2014起) + SMM 铅矿到港防城(a10127618, 月度294点/2019起) + Mysteel 进口铅精矿港口库存(ID01167590, 周度432点/2022起)。<br>
<strong style="color:#c9d1d9">数据质量：</strong>全球铅矿产量102点(2014-01起)；到港防城294点(2019-01起)；港口库存432点(2022-08起)。<br>
<strong style="color:#c9d1d9">3.x 边界：</strong>3.1.1=海外矿财报产量·季同步(正主=全球铅矿产量) · 3.1.2=分国别总量·月同步 · 3.1.3=国内矿产量·月同步 · 3.1.4=矿进口量·月同步 · 3.1.5=TC加工费·月先行 · 3.2.1=精炼产量·月同步 · 3.2.2=开工率检修·周同步 · 3.2.3=再生供应(已上线) · 3.2.4=冶炼利润供应弹性·日同步。"""

html = page_html(
    "铅(PB) 3.1.1 海外矿·财报产量",
    make_crumb("铅", "PB", "3", "供给", "3.1.1", "海外矿·财报产量", "1", 3),
    "ILZSG/SMM",
    h1, h2, h3, NOTE,
    "有色金属产业指标树 · 铅(PB) 3.1.1 海外矿·财报产量 · v1（3 图全真数据 · 全球铅矿产量 · 到港防城 · 港口库存）· indicators_v1.json v3.1",
    j1 + "\n" + j2 + "\n" + j3,
    CIDS,
    nav_back='<a href="pb_3_overview.html">← 回板块3总览</a> <a href="index.html">← 回主站</a>',
)
write_html("pb_311_overseas_mine.html", html)
